export function Icon({ name, size = 16, className }: { name: IconName; size?: number; className?: string }) {
  const px = iconSize(size);
  const gl = GITLAB[name];
  if (gl)
    return (
      <svg width={px} height={px} viewBox="0 0 16 16" fill="currentColor" className={className} aria-hidden>
        <use href={`/gitlab-icons.svg#${gl}`} />
      </svg>
    );
  const C = ICONS[name];
  return <C size={px} className={className} aria-hidden />;
}
