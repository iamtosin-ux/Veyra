export type IconName = keyof typeof ICONS;

/**
 * One icon treatment across Veyra: Remix line icons at 16px, or 12px beside caption-sized text.
 * Sizes from 20px up are kept for empty states and media controls.
 */
export const iconSize = (size: number) => (size >= 20 ? size : size <= 12 ? 12 : 16);

